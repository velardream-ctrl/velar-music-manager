import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const read=p=>fs.readFileSync(new URL('../'+p,import.meta.url),'utf8');
const code=read('ai-fallback.js'),lab=read('studio/ai-lab.js'),html=read('studio/index.html'),sw=read('sw.js');
new vm.Script(code);
assert.match(html,/\.\.\/ai-fallback\.js\?v=1/);
assert.match(html,/ai-lab\.js\?v=4/);
assert.match(sw,/ai-fallback\.js\?v=1/);
assert.match(sw,/fallback195/);
assert.match(read('index.html'),/ai-fallback\.js\?v=1/,'Public assistant loads fallback router');
const ctx={module:{exports:{}},window:{},Promise,Date,setTimeout,clearTimeout};
vm.runInNewContext(code,ctx);
const router=ctx.module.exports;
assert.equal(typeof router.offer,'function');
let localCalls=0, remoteCalls=0;
function local(){localCalls++;return {text:'Локальный DJ Velar работает'};}
const enabled={enabled:true,timeoutMs:1000,now:()=>1000};
let result=await router.offer(local,()=>{remoteCalls++;return Promise.resolve({reply:'AI ответил'});},enabled);
assert.equal(result.source,'ai');
assert.equal(localCalls,0);
router.reset();
result=await router.offer(local,()=>{remoteCalls++;return Promise.reject({code:'quota_exhausted'});},enabled);
assert.equal(result.source,'local');assert.equal(result.reason,'quota');
assert.equal(router.state(1000).cooldown,86400000);
const count=remoteCalls;
result=await router.offer(local,()=>{remoteCalls++;throw Error('Should not execute');},enabled);
assert.equal(result.reason,'cooldown');assert.equal(remoteCalls,count);
router.reset();
result=await router.offer(local,()=>{remoteCalls++;return Promise.reject(new Error('service down'));},enabled);
assert.equal(result.source,'local');
result=await router.offer(local,()=>new Promise(()=>{}),{enabled:true,timeoutMs:1000});
assert.equal(result.source,'local');assert.equal(result.reason,'timeout');
result=await router.offer(local,()=>{remoteCalls++;throw Error('Should not run');},{enabled:false});
assert.equal(result.reason,'ai-disabled');
assert.ok(localCalls>=5);
assert.match(lab,/Проверить отказ ИИ и резервный ответ/);
assert.match(lab,/quota_exhausted/);
console.log('PASS RUN-195: AI quota, timeout, disabled, outage all return local response; public chatbot remains local-only');