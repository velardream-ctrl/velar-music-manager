import fs from 'node:fs';
import vm from 'node:vm';
const read=p=>fs.readFileSync(new URL('../'+p,import.meta.url),'utf8');
const globals={window:{},console,Date,JSON,Number,Array,String,Error,isFinite};
vm.runInNewContext(read('landing-schema.js'),globals,{timeout:2000});
