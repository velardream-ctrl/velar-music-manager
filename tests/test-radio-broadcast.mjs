import assert from 'node:assert/strict';
import fs from 'node:fs';
import {spawnSync} from 'node:child_process';
const root=new URL('../',import.meta.url);
const read=p=>fs.readFileSync(new URL(p,root),'utf8');
const backend=read('radio-broadcast/functions/index.js');
const site=read('landing-public.js');
const editor=read('studio/landing-editor.js');
const schema=read('landing-schema.js');
const checker=spawnSync(process.execPath,['--check',new URL('radio-broadcast/functions/index.js',root).pathname],{encoding:'utf8'});
assert.equal(checker.status,0,checker.stderr);
assert.match(backend,/onCall\(/);
assert.match(backend,/defineSecret\('AZURACAST_API_KEY'\)/);
assert.match(backend,/email_verified/);
assert.match(backend,/sign_in_provider==='google\.com'/);
assert.match(backend,/vmm_admins/);
assert.match(backend,/admin\.data\(\)\.enabled!==true/);
assert.match(backend,/action!=='status'/);
assert.match(backend,/frontend\/start|frontend\/stop/);
assert.match(editor,/httpsCallable\('velarRadioControl'\)/);
assert.match(editor,/Начать трансляцию/);
assert.match(schema,/streamUrl/);
assert.match(site,/velar-radio-audio/);
assert.doesNotMatch(site,/AZURACAST_API_KEY|backend\/start/);
assert.doesNotMatch(editor,/AZURACAST_API_KEY/);
console.log('PASS: secured server broadcast scaffold; native stream separated from official embeds');
